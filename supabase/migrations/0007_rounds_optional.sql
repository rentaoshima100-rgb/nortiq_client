-- ============================================================================
-- ラウンド制を案件ごとに切れるようにする
--
-- 顧問契約のように「回数を数えない」案件がある。その場合でも
-- 撮影・差分・素材差し替えは使いたいので、ラウンド自体は内部で1本開いたままにし、
-- 締切・カウント・確認の運用だけを外す。
--
-- false のとき起きなくなること:
--   - 無操作フリーズ / 件数上限での即時フリーズ（8.2 / 8.5）
--   - 公開 → 確認 → カウント +1（8.6 / 5.4）
--   - クライアント画面の消化状況とフリーズ予告
-- 変わらないもの:
--   - 依頼の受付、ピン、切り出し、撮影、差分、素材差し替え、PR
-- ============================================================================

alter table projects add column if not exists rounds_enabled bool not null default true;

comment on column projects.rounds_enabled is
  'false にするとラウンドの締切・カウント・確認を行わない。依頼は1本の open ラウンドに貯まり続ける。';
