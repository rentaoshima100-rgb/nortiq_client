-- 依頼ごとの社内メモ（依頼文より優先される値）
--
-- 修正を当てるのはやめ、Claude Code に渡すプロンプトを出す形にした。
-- そのとき一番効くのが**依頼文に無い値**で、それを持っているのは社内。
-- クライアントは「許可番号を入れて」としか書かない。番号は社内にある。
--
-- これまで実行時の引数として渡していたので残らなかった。プロンプトは
-- 何度も作り直すものなので、依頼にぶら下げて残す。
--
-- 画面の写真は無条件で必須にした（案件ごとの切り替えはやめた）。
-- 目印は文言を頼りにしており、直せばその文言が変わる。写真が唯一
-- 残る手がかりになるので、例外を作らない。

alter table requests add column if not exists staff_note text;

comment on column requests.staff_note is
  '社内が足す補足。依頼文に無い値（番号・正式名称・どの写真か）を書く。'
  'Claude Code に渡すプロンプトでは、依頼文より優先すると明記して載せる。';
